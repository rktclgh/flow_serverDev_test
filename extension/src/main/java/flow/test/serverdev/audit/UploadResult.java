package flow.test.serverdev.audit;

/**
 * 업로드 시도의 결말. (SPEC §3.2)
 *
 * <p>{@link #PENDING} 은 두 단계 기록 프로토콜의 중간 상태다. Postgres 와 오브젝트
 * 스토리지에 걸친 원자성은 2PC 없이 성립하지 않으므로, 저장을 시작하기 <b>전에</b>
 * 자리를 잡아두고 성공/실패에 따라 확정한다.
 *
 * <p>그 결과 잔여물은 언제나 {@code PENDING} 으로 남아 <b>탐지 가능</b>하다.
 * 조용히 새는 객체가 생기지 않는다는 것이 이 상태의 존재 이유다.
 */
public enum UploadResult {

	/** 저장까지 끝났다. 이 상태의 행은 객체가 반드시 존재한다. */
	ALLOWED,

	/** 정책이 거부했다. 저장하지 않았으므로 키가 없다. */
	BLOCKED,

	/** 정책과 무관한 실패(스토리지 장애 등). */
	ERROR,

	/** 키는 정해졌고 저장이 끝나지 않았다. 확정되지 않은 중간 상태. */
	PENDING
}
